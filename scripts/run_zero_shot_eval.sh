#!/usr/bin/env bash
# =============================================================================
# Zero-Shot Evaluation: MRL + BAM-A + BAM-B on TREC-COVID / SciDocs / Climate-FEVER
#
# Uses models trained ONLY on educational data — no BEIR-specific training.
# Tests zero-shot domain transfer to scientific / biomedical retrieval.
#
# Usage:
#   chmod +x scripts/run_zero_shot_eval.sh
#   ./scripts/run_zero_shot_eval.sh
#
#   # Override checkpoint paths (e.g. after re-training):
#   MRL_CKPT=/my/mrl/best ./scripts/run_zero_shot_eval.sh
#
#   # Run on specific datasets only:
#   DATASETS="trec-covid scidocs" ./scripts/run_zero_shot_eval.sh
#
# Requirements:
#   pip install beir transformers torch sentence-transformers faiss-cpu pyyaml
#   (beir install: pip install beir  or  pip install beir-retrieval)
# =============================================================================

set -euo pipefail

# ─── Educational model checkpoints (trained once, evaluated zero-shot) ───────
MRL_CKPT="${MRL_CKPT:-/tmp/multi-domain/educational/mrl/best}"
BAM_B_CKPT="${BAM_B_CKPT:-/tmp/multi-domain/educational/bam_b/best_bsr}"
BAM_A_CKPT="${BAM_A_CKPT:-/tmp/multi-domain/educational/bam_a/best_bsr}"

# ─── Config files (generated by run_full_pipeline.sh for the educational dataset) ─
MRL_CFG="${MRL_CFG:-results/multi_domain/educational/configs/mrl.yaml}"
BAM_B_CFG="${BAM_B_CFG:-results/multi_domain/educational/configs/bam_b.yaml}"
BAM_A_CFG="${BAM_A_CFG:-results/multi_domain/educational/configs/bam_a.yaml}"

# ─── Fallback to base configs if per-dataset configs don't exist yet ─────────
if [[ ! -f "$MRL_CFG" ]]; then
    echo "  Per-dataset MRL config not found at $MRL_CFG — using base config."
    MRL_CFG="configs/mrl_e5large.yaml"
fi
if [[ ! -f "$BAM_B_CFG" ]]; then
    echo "  Per-dataset BAM-B config not found at $BAM_B_CFG — using base config."
    BAM_B_CFG="configs/bam_optionb_e5large.yaml"
fi

# ─── Evaluation settings ─────────────────────────────────────────────────────
DATASETS="${DATASETS:-trec-covid scidocs climate-fever}"
OUTPUT_DIR="${OUTPUT_DIR:-results/zero_shot}"
NLI_MODEL="${NLI_MODEL:-MoritzLaurer/DeBERTa-v3-large-mnli-fever-anli-ling-wanli}"
NLI_BATCH_SIZE="${NLI_BATCH_SIZE:-32}"

# ─── Sanity checks ────────────────────────────────────────────────────────────
die() { echo "ERROR: $*" >&2; exit 1; }
log() { echo ""; echo "══════════════════════════════════════════════════════"; \
        echo "  [$(date '+%H:%M:%S')]  $*"; \
        echo "══════════════════════════════════════════════════════"; }

[[ -f "$MRL_CFG" ]]   || die "MRL config not found: $MRL_CFG"
[[ -f "$BAM_B_CFG" ]] || die "BAM-B config not found: $BAM_B_CFG"

[[ -d "$MRL_CKPT" ]]   || echo "  WARNING: MRL checkpoint directory not found: $MRL_CKPT"
[[ -d "$BAM_B_CKPT" ]] || echo "  WARNING: BAM-B checkpoint directory not found: $BAM_B_CKPT"

mkdir -p "$OUTPUT_DIR"

# ─── Build optional BAM-A arguments ─────────────────────────────────────────
BAM_A_ARGS=""
if [[ -d "$BAM_A_CKPT" ]] && [[ -f "$BAM_A_CFG" ]]; then
    BAM_A_ARGS="--bam_a_checkpoint $BAM_A_CKPT --bam_a_config $BAM_A_CFG"
    echo "  BAM-A checkpoint found — will evaluate BAM-A as well."
else
    echo "  BAM-A checkpoint not found ($BAM_A_CKPT) or config missing — skipping BAM-A."
fi

# ─── Run zero-shot evaluation ─────────────────────────────────────────────────
log "ZERO-SHOT EVAL  datasets: $DATASETS"
echo "  MRL  : $MRL_CKPT  (config: $MRL_CFG)"
echo "  BAM-B: $BAM_B_CKPT  (config: $BAM_B_CFG)"
echo "  Output: $OUTPUT_DIR"
echo "  NLI model: $NLI_MODEL"

python scripts/eval_zero_shot.py \
    --mrl_checkpoint   "$MRL_CKPT"   \
    --mrl_config       "$MRL_CFG"    \
    --bam_b_checkpoint "$BAM_B_CKPT" \
    --bam_b_config     "$BAM_B_CFG"  \
    $BAM_A_ARGS                      \
    --datasets         $DATASETS     \
    --output_dir       "$OUTPUT_DIR" \
    --nli_model        "$NLI_MODEL"  \
    --nli_batch_size   "$NLI_BATCH_SIZE"

log "DONE — results in $OUTPUT_DIR"
echo ""
echo "  Key output files:"
echo "    $OUTPUT_DIR/zero_shot_results.json  (all datasets combined)"
for DS in $DATASETS; do
    echo "    $OUTPUT_DIR/${DS}.json"
done
